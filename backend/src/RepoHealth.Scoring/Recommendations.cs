/// Строит приоритизированные рекомендации по готовому отчёту.
///
/// Идея простая: каждая часть оценки знает, сколько баллов она
/// недобрала и почему. Недобор — это и есть проблема, а его размер
/// с учётом веса категории — это то, сколько вернёт исправление.
