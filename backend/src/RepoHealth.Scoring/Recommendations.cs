    public static List<Recommendation> For(HealthReport report)
    {
        var result = new List<Recommendation>();

        foreach (var category in report.Categories)
        {
            if (category.Status != CategoryStatus.Scored)
                continue;

            foreach (var part in category.Parts)
            {
                var gap = part.MaxPoints - part.Points;

                // Вклад в итог считаем через вес, который категория
                // получила на самом деле после перенормировки.
                var gain = Math.Round(gap * category.AppliedWeight / 100, 1);

                if (gain < SmallestGain)
                    continue;

                if (!Library.TryGetValue(part.Name, out var advice))
                    continue;

                result.Add(new Recommendation
                {
                    Category = category.Name,
                    Problem = advice.Problem,
                    Why = advice.Why,
                    Action = advice.Action,
                    Evidence = part.Explanation,
                    ExpectedGain = gain,
                    Priority = PriorityFor(gain)
                });
            }
        }

        // Сначала то, что даёт больший прирост.
        return result
            .OrderByDescending(item => item.ExpectedGain)
            .ThenBy(item => item.Category)
            .ToList();
    }

    private static Priority PriorityFor(double gain) => gain switch
    {
        >= HighPriorityGain => Priority.High,
        >= MediumPriorityGain => Priority.Medium,
        _ => Priority.Low
    };
